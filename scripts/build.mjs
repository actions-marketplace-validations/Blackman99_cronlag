import { build } from "esbuild";
import { chmodSync, readFileSync, writeFileSync } from "node:fs";

// The catch-up engine for `cronlag worker --target cloudflare`: one self-contained, dependency-free script
// (cronlag's own collect + planCatchup + cron + yaml), embedded in the CLI as a string. Committed, like dist/.
const engine = await build({ bundle: true, platform: "neutral", mainFields: ["module", "main"], format: "iife", globalName: "cronlag", target: "es2022", minify: true, write: false, legalComments: "none", entryPoints: ["src/worker/engine.ts"], logLevel: "warning" });
const engineTs = `// Generated by scripts/build.mjs from src/worker/engine.ts. Do not edit.\nexport const ENGINE = ${JSON.stringify(engine.outputFiles[0].text.replace(/^"use strict";/, ""))};\n`;
const enginePath = "src/worker/engine.generated.ts";
let prev = "";
try { prev = readFileSync(enginePath, "utf8"); } catch {}
if (prev !== engineTs) writeFileSync(enginePath, engineTs);

const common = { bundle: true, platform: "node", target: "node18", format: "esm", legalComments: "none", logLevel: "warning" };
await build({ ...common, entryPoints: ["src/cli.ts"], outfile: "dist/cli.js", banner: { js: "#!/usr/bin/env node\nimport { createRequire as __cr } from 'module'; const require = __cr(import.meta.url);" } });
await build({ ...common, entryPoints: ["src/index.ts"], outfile: "dist/index.js", banner: { js: "import { createRequire as __cr } from 'module'; const require = __cr(import.meta.url);" } });
await build({ ...common, entryPoints: ["src/action.ts"], outfile: "dist/action.js", target: "node20", banner: { js: "import { createRequire as __cr } from 'module'; const require = __cr(import.meta.url);" } });
// Browser bundle for the landing page live demo (no Node APIs).
await build({ bundle: true, platform: "browser", format: "esm", target: "es2020", minify: true, entryPoints: ["src/browser.ts"], outfile: "site/cronlag.js", legalComments: "none" });
chmodSync("dist/cli.js", 0o755);
console.log("built src/worker/engine.generated.ts dist/cli.js dist/index.js dist/action.js site/cronlag.js");
